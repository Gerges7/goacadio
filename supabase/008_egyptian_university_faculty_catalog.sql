UPDATE public.universities u
SET name_en=s.name_en,name_ar=s.name_ar,institution_type=s.institution_type,
    source_url=s.source_url,is_published=true
FROM _goacadio_egypt_universities s
WHERE u.country_code='EG'
  AND (lower(btrim(u.name_en))=lower(btrim(s.name_en))
    OR (u.name_ar IS NOT NULL AND btrim(u.name_ar)=btrim(s.name_ar)));

INSERT INTO public.universities(country_code,name_en,name_ar,institution_type,source_url,is_published)
SELECT 'EG',s.name_en,s.name_ar,s.institution_type,s.source_url,true
FROM _goacadio_egypt_universities s
WHERE NOT EXISTS (
  SELECT 1 FROM public.universities u
  WHERE u.country_code='EG'
    AND (lower(btrim(u.name_en))=lower(btrim(s.name_en))
      OR (u.name_ar IS NOT NULL AND btrim(u.name_ar)=btrim(s.name_ar)))
);

