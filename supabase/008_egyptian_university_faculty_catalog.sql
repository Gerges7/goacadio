SET name_ar=s.name_ar,source_url=s.source_url,is_published=true
FROM _goacadio_egypt_faculties s
JOIN public.universities u
  ON u.country_code='EG'
 AND lower(btrim(u.name_en))=lower(btrim(s.university_name_en))
WHERE f.university_id=u.id
  AND lower(btrim(f.name_en))=lower(btrim(s.name_en));

INSERT INTO public.faculties(university_id,name_en,name_ar,source_url,is_published)
SELECT u.id,s.name_en,s.name_ar,s.source_url,true
FROM _goacadio_egypt_faculties s
JOIN public.universities u
  ON u.country_code='EG'
 AND lower(btrim(u.name_en))=lower(btrim(s.university_name_en))
WHERE NOT EXISTS (
  SELECT 1 FROM public.faculties f
  WHERE f.university_id=u.id
    AND lower(btrim(f.name_en))=lower(btrim(s.name_en))
);

