ALTER TABLE public.faculties ADD COLUMN IF NOT EXISTS source_url text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname='universities_institution_type_check'
      AND conrelid='public.universities'::regclass
  ) THEN
    ALTER TABLE public.universities ADD CONSTRAINT universities_institution_type_check
    CHECK (institution_type IN (
      'public','public_special','private','national',
      'government_technological','private_technological',
      'international_branch','special_nature','other'
    ));
  END IF;
END $$;

