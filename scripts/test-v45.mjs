/** GoAcadio V4.5: Saudi university catalog, support channels and theme checks. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const sql = read('supabase/009_saudi_university_catalog.sql');
const universities = read('app/routes/universities.tsx');
const contact = read('app/lib/contact.ts');
const contactPage = read('app/routes/contact.tsx');
const about = read('app/routes/about.tsx');
const chrome = read('app/components/chrome.tsx');
const theme = read('app/components/theme-provider.tsx');
const rootPage = read('app/root.tsx');
const styles = read('app/styles.css');
const pkg = JSON.parse(read('package.json'));

const block = sql.match(/INSERT INTO _goacadio_saudi_universities[\s\S]*?VALUES\n([\s\S]*?);/);
assert.ok(block, 'Saudi seed block exists');
const rows = block[1].split('\n').filter(line => line.trim().startsWith("('"));
assert.equal(rows.length, 44, '44 Saudi universities are seeded');
assert.equal(rows.filter(line => line.includes(",'public',")).length, 29, '29 public Saudi universities');
assert.equal(rows.filter(line => line.includes(",'private',")).length, 15, '15 private Saudi universities');
assert.match(sql, /VALUES\('SA','Saudi Arabia','السعودية',true\)/);
assert.match(sql, /ON CONFLICT\(code\)/);
assert.match(sql, /is_published=true/);
assert.doesNotMatch(sql, /\bDELETE\s+FROM\b|\bDROP\s+TABLE\b/i, 'migration is additive');
assert.match(universities, /\.in\('country_code', \['EG', 'SA'\]\)/);
assert.match(universities, /countryCode/);
assert.match(universities, /Saudi Arabia/);
assert.match(contact, /support@goacadio\.com/);
assert.match(contact, /@GoAcadio/);
assert.doesNotMatch(about, /gergesmorad17@gmail\.com/);
assert.match(contactPage, /OFFICIAL_WHATSAPP_USERNAME/);
assert.match(contactPage, /copyWhatsAppUsername/);
assert.match(chrome, /useTheme/);
assert.match(chrome, /theme-toggle/);
assert.match(chrome, /OFFICIAL_SUPPORT_EMAIL/);
assert.match(chrome, /OFFICIAL_WHATSAPP_USERNAME/);
assert.match(theme, /localStorage\.setItem/);
assert.match(theme, /data-theme/);
assert.match(rootPage, /ThemeProvider/);
assert.match(rootPage, /themeInitScript/);
assert.match(styles, /:root\[data-theme="dark"\]/);
assert.match(styles, /@media print/);
assert.equal(pkg.scripts['test:v45'], 'node scripts/test-v45.mjs');
assert.ok(pkg.scripts['check:ci'].includes('npm run test:v45'));
console.log('V4.5 checks passed: 44 Saudi universities, updated support channels and light/dark theme.');
